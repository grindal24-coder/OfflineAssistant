package com.offlineassistant.ai

/** Один найденный результат поиска — заголовок + короткий сниппет текста. */
data class SearchSnippet(val title: String, val snippet: String, val url: String)

/**
 * Абстракция над поисковым провайдером, используемым для ASK-intent'ов
 * (см. IntentType.ASK в commands/Intent.kt). Позволяет менять провайдера
 * без изменений в WebAnswerHandler/LlamaEngine.
 *
 * ВАЖНО про выбор провайдера (честно, по опыту): полноценного бесплатного
 * общего веб-поиска без ключа и без жёстких лимитов на рынке практически
 * нет. Варианты:
 *
 *  1. BraveWebSearchClient (реализовано ниже) — нужен бесплатный API-ключ
 *     (см. https://brave.com/search/api/), у бесплатного тира есть лимит
 *     запросов/месяц, но качество результатов хорошее, годится для голосового
 *     ассистента с невысокой частотой запросов.
 *  2. DuckDuckGoInstantAnswerClient (реализовано ниже) — вообще без ключа,
 *     но их официальный Instant Answer API отвечает только на "справочные"
 *     запросы (определения, факты из их баз типа Википедии) — на "что было
 *     вчера в новостях" или произвольный современный вопрос он чаще всего
 *     вернёт пустой ответ. Используется как fallback, когда ключ Brave не настроен.
 *  3. Самостоятельно поднятый SearXNG (не реализовано) — бесплатно навсегда,
 *     агрегирует результаты нескольких движков, но требует своего сервера
 *     (VPS/домашний хостинг) — усложняет "просто собрать APK", не стал
 *     делать это дефолтом.
 */
interface WebSearchClient {
    /** Возвращает до maxResults сниппетов, либо пустой список, если ничего не нашлось/нет сети. */
    suspend fun search(query: String, maxResults: Int = 3): List<SearchSnippet>
}
